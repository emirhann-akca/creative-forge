_MONTHS = {
    "tr": ("Oca", "Şub", "Mar", "Nis", "May", "Haz", "Tem", "Ağu", "Eyl", "Eki", "Kas", "Ara"),
    "en": ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"),
}


def fmt_num(v: Any, lang: str = "tr", digits: int = 2) -> str:
    """``1234.5`` -> ``1.234,50`` (tr) or ``1,234.50`` (en); ``None`` -> an em dash; anything else as text."""
    if v is None or v == "":
        return "—"
    if isinstance(v, bool) or not isinstance(v, int | float):
        return str(v)
    if v != v:  # NaN
        return "—"
    s = f"{v:,.{max(0, int(digits))}f}"
    if lang == "tr":
        s = s.replace(",", "\0").replace(".", ",").replace("\0", ".")
    return s


def fmt_pct(v: Any, lang: str = "tr", digits: int = 1, sign: bool = False) -> str:
    """A number of percent: ``%26,9`` / ``+%26,9`` in Turkish, ``26.9%`` / ``+26.9%`` in English."""
    if v is None or isinstance(v, bool) or not isinstance(v, int | float) or v != v:
        return "—"
    body = fmt_num(abs(v), lang, digits)
    pre = ("+" if v > 0 else "−" if v < 0 and body.strip("0,.") else "") if sign else ("−" if v < 0 else "")
    return f"{pre}%{body}" if lang == "tr" else f"{pre}{body}%"


def fmt_prob(p: Any, lang: str = "tr") -> str:
    """A probability as a percentage, with the ends shown as bounds (a Monte Carlo 1.0 is not certainty)."""
    if p is None or isinstance(p, bool) or not isinstance(p, int | float):
        return "—"
    if p >= 0.995:
        return ">%99" if lang == "tr" else ">99%"
    if p <= 0.005:
        return "<%1" if lang == "tr" else "<1%"
    return fmt_pct(p * 100, lang, 0)


def fmt_date(v: Any, lang: str = "tr") -> str:
    """A Unix time, an ISO date or an ISO timestamp, as ``13 Kas 2026 14:05`` in local time."""
    if v in (None, ""):
        return "—"
    try:
        if isinstance(v, int | float):
            d = datetime.fromtimestamp(float(v))
        else:
            s = str(v)
            if len(s) == 10:
                d = datetime.fromisoformat(s)
                return f"{d.day} {_MONTHS.get(lang, _MONTHS['en'])[d.month - 1]} {d.year}"
            d = datetime.fromisoformat(s.replace("Z", "+00:00"))
            if d.tzinfo is not None:
                d = d.astimezone().replace(tzinfo=None)
    except (ValueError, OverflowError, OSError):
        return str(v)
    return f"{d.day} {_MONTHS.get(lang, _MONTHS['en'])[d.month - 1]} {d.year} {d:%H:%M}"


def review_error(message: str, lang: str) -> str:
    """``review.decide``'s error in the page's language; unknown messages pass through unchanged."""
    t = T.get(lang, T["tr"])
    if "rejection needs a note" in message:
        return t.err_reject_note
    if message.startswith("decision must be one of"):
        return t.err_decision
    if "is not an export of this run" in message:
        return t.err_not_export
    return message
